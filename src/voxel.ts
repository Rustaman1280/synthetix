/**
 * @crustdev/synthetix - Voxel Region Generator
 * 3D voxel density sampling, material assignment, and Roblox WriteVoxels Luau export.
 */

import { NoiseGenerator } from "./noise";

export type VoxelMaterial = "Air" | "Water" | "Sand" | "Grass" | "Rock" | "Basalt" | "Snow";

export type VoxelRegionOptions = {
  sizeX?: number;
  sizeY?: number;
  sizeZ?: number;
  scale?: number;
  seaLevel?: number;
};

export type VoxelPoint = {
  x: number;
  y: number;
  z: number;
  density: number; // 0 (empty air) to 1 (solid)
  material: VoxelMaterial;
};

export class VoxelRegion {
  public readonly sizeX: number;
  public readonly sizeY: number;
  public readonly sizeZ: number;
  public readonly voxels: VoxelPoint[];

  constructor(noise: NoiseGenerator, options: VoxelRegionOptions = {}) {
    this.sizeX = options.sizeX ?? 16;
    this.sizeY = options.sizeY ?? 16;
    this.sizeZ = options.sizeZ ?? 16;
    const scale = options.scale ?? 24;
    const seaLevel = options.seaLevel ?? 4;

    this.voxels = [];

    for (let y = 0; y < this.sizeY; y++) {
      for (let z = 0; z < this.sizeZ; z++) {
        for (let x = 0; x < this.sizeX; x++) {
          // 3D noise sample
          const noise3d = noise.fbm3D(x / scale, y / scale, z / scale, 3);
          // Height gradient falloff (higher y has lower density)
          const heightFalloff = 1.0 - y / this.sizeY;
          const density = Math.max(0, Math.min(1, noise3d * 0.7 + heightFalloff * 0.6 - 0.2));

          let material: VoxelMaterial = "Air";

          if (density > 0.1) {
            if (y > this.sizeY * 0.8) {
              material = "Snow";
            } else if (y > this.sizeY * 0.5) {
              material = "Rock";
            } else if (y === seaLevel || y === seaLevel + 1) {
              material = "Sand";
            } else if (y < seaLevel) {
              material = "Basalt";
            } else {
              material = "Grass";
            }
          } else if (y <= seaLevel) {
            material = "Water";
          }

          this.voxels.push({ x, y, z, density, material });
        }
      }
    }
  }

  /**
   * Generates typed Luau code for Roblox workspace.Terrain:WriteVoxels()
   */
  public toRobloxTerrainTable(): string {
    const lines: string[] = [
      "-- Generated by @crustdev/synthetix",
      `-- Region: ${this.sizeX}x${this.sizeY}x${this.sizeZ}`,
      "local RegionData = {",
      `\tSize = Vector3.new(${this.sizeX}, ${this.sizeY}, ${this.sizeZ}),`,
      "\tVoxels = {",
    ];

    // Only export non-air voxels to keep payload lean
    const solidVoxels = this.voxels.filter((v) => v.material !== "Air");
    for (const v of solidVoxels.slice(0, 100)) {
      lines.push(
        `\t\t{ Pos = Vector3.new(${v.x}, ${v.y}, ${v.z}), Mat = Enum.Material.${v.material}, Occ = ${v.density.toFixed(2)} },`
      );
    }

    if (solidVoxels.length > 100) {
      lines.push(`\t\t-- ... and ${solidVoxels.length - 100} more voxel points`);
    }

    lines.push("\t},", "}", "return RegionData");
    return lines.join("\n");
  }
}
